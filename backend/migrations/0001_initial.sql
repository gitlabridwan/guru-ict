PRAGMA foreign_keys=ON;
CREATE TABLE IF NOT EXISTS teachers (
 id INTEGER PRIMARY KEY AUTOINCREMENT, email TEXT NOT NULL UNIQUE COLLATE NOCASE,
 nama TEXT NOT NULL, wa TEXT NOT NULL DEFAULT '', sekolah TEXT NOT NULL DEFAULT '',
 password TEXT, google_sub TEXT UNIQUE, status TEXT NOT NULL DEFAULT 'menunggu',
 sampai INTEGER NOT NULL DEFAULT 0, maks_kelas INTEGER NOT NULL DEFAULT 20,
 created INTEGER NOT NULL, draft TEXT, draft_pk TEXT NOT NULL DEFAULT '', draft_at INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS auth_sessions (
 hash TEXT PRIMARY KEY, teacher_id INTEGER NOT NULL REFERENCES teachers(id) ON DELETE CASCADE,
 expires INTEGER NOT NULL, created INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS packs (
 code TEXT PRIMARY KEY, teacher_id INTEGER NOT NULL REFERENCES teachers(id),
 data TEXT NOT NULL, updated INTEGER NOT NULL, public INTEGER NOT NULL DEFAULT 0,
 bank INTEGER NOT NULL DEFAULT 0, views INTEGER NOT NULL DEFAULT 0, uses INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS classes (
 code TEXT PRIMARY KEY, teacher_id INTEGER NOT NULL REFERENCES teachers(id),
 name TEXT NOT NULL, guru TEXT NOT NULL, pin TEXT NOT NULL,
 pack_code TEXT NOT NULL DEFAULT '', pack TEXT NOT NULL, updated INTEGER NOT NULL,
 locked INTEGER NOT NULL DEFAULT 0, rekap TEXT NOT NULL DEFAULT '{}'
);
CREATE TABLE IF NOT EXISTS pack_versions (
 class_code TEXT NOT NULL REFERENCES classes(code) ON DELETE CASCADE,
 version INTEGER NOT NULL, data TEXT NOT NULL, PRIMARY KEY(class_code,version)
);
CREATE TABLE IF NOT EXISTS students (
 id INTEGER PRIMARY KEY AUTOINCREMENT, class_code TEXT NOT NULL REFERENCES classes(code) ON DELETE CASCADE,
 name TEXT NOT NULL, absen INTEGER NOT NULL, token_hash TEXT NOT NULL UNIQUE,
 active INTEGER NOT NULL, blocked INTEGER NOT NULL DEFAULT 0, UNIQUE(class_code,absen)
);
CREATE TABLE IF NOT EXISTS challenges (
 id INTEGER PRIMARY KEY AUTOINCREMENT, class_code TEXT NOT NULL REFERENCES classes(code) ON DELETE CASCADE,
 data TEXT NOT NULL, pack TEXT NOT NULL, main_code TEXT NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS starts (
 challenge_id INTEGER NOT NULL REFERENCES challenges(id) ON DELETE CASCADE,
 student_id INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
 started INTEGER NOT NULL, seed INTEGER NOT NULL, PRIMARY KEY(challenge_id,student_id)
);
CREATE TABLE IF NOT EXISTS records (
 id INTEGER PRIMARY KEY AUTOINCREMENT, class_code TEXT NOT NULL REFERENCES classes(code) ON DELETE CASCADE,
 student_id INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
 cid TEXT NOT NULL, data TEXT NOT NULL, created INTEGER NOT NULL,
 UNIQUE(student_id,cid)
);
CREATE INDEX IF NOT EXISTS records_class ON records(class_code,created);
CREATE INDEX IF NOT EXISTS records_student ON records(student_id);
CREATE TABLE IF NOT EXISTS companions (
 id INTEGER PRIMARY KEY AUTOINCREMENT, class_code TEXT NOT NULL REFERENCES classes(code) ON DELETE CASCADE,
 name TEXT NOT NULL, invite_hash TEXT NOT NULL UNIQUE, invite_code TEXT NOT NULL,
 token_hash TEXT UNIQUE, used INTEGER NOT NULL DEFAULT 0, active INTEGER NOT NULL DEFAULT 0, revoked INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS payments (
 id INTEGER PRIMARY KEY AUTOINCREMENT, teacher_id INTEGER NOT NULL REFERENCES teachers(id),
 t INTEGER NOT NULL, nominal INTEGER NOT NULL DEFAULT 0, ket TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS limits (
 key TEXT PRIMARY KEY, window INTEGER NOT NULL, count INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS audit (
 id INTEGER PRIMARY KEY AUTOINCREMENT, actor TEXT NOT NULL, action TEXT NOT NULL,
 target TEXT NOT NULL, t INTEGER NOT NULL
);
